CREATE TABLE IF NOT EXISTS users (
 id CHAR(36) PRIMARY KEY, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS sessions (
 sid VARCHAR(128) PRIMARY KEY, data MEDIUMTEXT NOT NULL, expires_at BIGINT NOT NULL,
 INDEX sessions_expiry (expires_at)
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS media (
 id CHAR(36) PRIMARY KEY, name VARCHAR(255) NOT NULL, mime VARCHAR(100) NOT NULL,
 alt VARCHAR(500) NOT NULL DEFAULT '', size INT NOT NULL, bytes MEDIUMBLOB NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS content (
 id CHAR(36) PRIMARY KEY, collection VARCHAR(32) NOT NULL, slug VARCHAR(180) NOT NULL,
 title VARCHAR(255) NOT NULL, summary TEXT NOT NULL, body MEDIUMTEXT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'draft', featured BOOLEAN NOT NULL DEFAULT FALSE,
 sort_order INT NOT NULL DEFAULT 0, fields JSON NOT NULL,
 seo_title VARCHAR(255) NOT NULL DEFAULT '', seo_description VARCHAR(500) NOT NULL DEFAULT '',
 published_at DATETIME NULL, deleted_at DATETIME NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 version INT NOT NULL DEFAULT 1,
 UNIQUE KEY content_slug (collection, slug), INDEX public_content (collection,status,deleted_at,sort_order),
 INDEX content_published (published_at)
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS content_media (
 content_id CHAR(36) NOT NULL, media_id CHAR(36) NOT NULL,
 PRIMARY KEY(content_id,media_id),
 FOREIGN KEY(content_id) REFERENCES content(id) ON DELETE CASCADE,
 FOREIGN KEY(media_id) REFERENCES media(id) ON DELETE RESTRICT
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS settings (
 id VARCHAR(32) PRIMARY KEY, value JSON NOT NULL, version INT NOT NULL DEFAULT 1,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS settings_media (
 settings_id VARCHAR(32) NOT NULL, media_id CHAR(36) NOT NULL,
 PRIMARY KEY(settings_id,media_id),
 FOREIGN KEY(settings_id) REFERENCES settings(id) ON DELETE CASCADE,
 FOREIGN KEY(media_id) REFERENCES media(id) ON DELETE RESTRICT
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS requests (
 id CHAR(36) PRIMARY KEY, kind VARCHAR(16) NOT NULL, name VARCHAR(150) NOT NULL,
 email VARCHAR(254) NOT NULL, phone VARCHAR(50) NOT NULL, service VARCHAR(255) NOT NULL,
 message TEXT NOT NULL, requested_at DATETIME NULL, timezone VARCHAR(100) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'new', notes TEXT NOT NULL,
 dedup_key CHAR(36) NOT NULL UNIQUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX requests_status (kind,status,created_at)
) CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
